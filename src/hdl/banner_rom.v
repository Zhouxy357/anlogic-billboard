//============================================================================
// banner_rom.v  ——  字幕条点阵 ROM（M4 模块的“字库”）
//---------------------------------------------------------------------------
// 字幕条规格：宽 BAN_W = 2048 像素，高 32 像素，每像素 1 bit（1 = 文字）。
// 存储方式：把每一行横向按 32 像素打包成 1 个 32bit 字。
//           一条 2048 像素宽的行 = 64 个字。
//           32 行 × 64 字 = 2048 个字。
//   ROM 深度 = 2048，位宽 = 32。
//   读地址 = 行号 × 64 + (列号 >> 5)
//   取哪一位 = 31 - (列号 & 31)      （保证文字左右方向正确）
//
// 数据来源：由 tools/gen_banner.py 生成的 banner_rom.hex
//           每行 8 位十六进制。若没有生成该文件，综合会读到全 0，
//           表现为“字幕条是纯色底、没有文字”，不会导致画面异常。
//
// 【重要】若报找不到 banner_rom.hex，同 audio_rom.v 的处理方式：
//         把 hex 放到 Sim 的 sim/ 目录（仿真）或 TD 工程目录（综合）；
//         文件名只能写成字面量（不能用 parameter 传）。
//============================================================================
`timescale 1ns / 1ps

module banner_rom (
    input  wire        clk,
    input  wire [10:0] addr,      // 0..2047
    output reg  [31:0] dout
);

    reg [31:0] mem [0:2047];

    integer i;
    initial begin
        for (i = 0; i < 2048; i = i + 1)
            mem[i] = 32'h00000000;
        $readmemh("banner_rom.hex", mem);
    end

    always @(posedge clk)
        dout <= mem[addr];

endmodule
