`timescale 1ns / 1ps
//============================================================================
// led_test_top.v —— 移植第 1 步：最小点灯验证工程
//----------------------------------------------------------------------------
// 目的：在改任何业务代码之前，先用一个"只有 3 个端口"的最小工程，
//       验证两件最基本的事：
//         ① 引脚表对不对（LED 真的亮了）
//         ② 晶振频率对不对（闪烁快慢 = 频率的直接读数）
//
// 为什么闪烁能测频率：
//   代码里按 CLK_FREQ=50MHz 分频到 1Hz（亮 1 秒 / 灭 1 秒）。
//   如果板上晶振其实是 25MHz，实测闪烁就会变成 0.5Hz（亮 2 秒 / 灭 2 秒）。
//   用手机秒表数 10 秒里的亮灭次数，就能反推晶振频率，误差足够判断。
//
//   ┌──────────────┬────────────────┬──────────────────┐
//   │ 数 10 秒亮几次 │ 实测频率        │ 结论              │
//   ├──────────────┼────────────────┼──────────────────┤
//   │ 约 5 次      │ 1Hz 闪烁正常    │ 晶振 ≈ 50MHz ✓    │
//   │ 约 2~3 次    │ 偏慢一半        │ 晶振 ≈ 25MHz      │
//   │ 约 10 次     │ 偏快一倍        │ 晶振 ≈ 100MHz     │
//   │ 完全不亮     │ —              │ 引脚错 / 没烧进去 │
//   └──────────────┴────────────────┴──────────────────┘
//
// 端口只有 3 个（clk / rst_n / led），所以在 pin.adc 里只要填 3 行，
// 是最快能烧上板的东西。烧通了，链路（下载器/板子/时钟）就全部确认了。
//============================================================================

module led_test_top #(
    parameter integer CLK_FREQ = 50_000_000
)(
    input  wire clk,
    input  wire rst_n,
    output wire led
);

    localparam integer HALF = CLK_FREQ / 2;   // 半个周期 = 0.5 秒

    reg [31:0] cnt;
    reg        blink;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cnt   <= 32'd0;
            blink <= 1'b0;
        end
        else if (cnt >= HALF - 1) begin
            cnt   <= 32'd0;
            blink <= ~blink;
        end
        else begin
            cnt   <= cnt + 32'd1;
        end
    end

    // 板上的 LED 可能是高电平点亮，也可能低电平点亮。
    // 不确定时先用高电平点亮；若上板是"常亮后闪"而不是"常灭后闪"，
    // 说明极性相反，把下面这行的 blink 改成 ~blink 即可（不影响判断成功与否）。
    assign led = blink;

endmodule
